-- 072_seeds_wanted.sql
-- Ручные позиции в «Список покупок»: культура, которой ещё нет ни на участке, ни в коробке,
-- но которую пользователь хочет купить (новый сорт, культура для будущего сезона).
-- wanted=true — «хочу купить», не занимает место физической коробки (GET /seeds её не отдаёт).
-- wanted=false (по умолчанию) — прежнее поведение, реальный пакетик в инвентаре.
-- Отметить купленным = снять флаг (PATCH /seeds/:id {wanted:false}) — запись становится обычным
-- пакетиком, не новая сущность и не повторный ввод данных.

ALTER TABLE seeds ADD COLUMN IF NOT EXISTS wanted BOOLEAN NOT NULL DEFAULT false;
