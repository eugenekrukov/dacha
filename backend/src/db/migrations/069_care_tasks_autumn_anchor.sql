-- Migration 069: осенние работы привязаны к концу вегетации.
--
-- Было: day_offset у всех задач считался от НАЧАЛА сезона. Для осенних работ это неверно —
-- длина сезона по зонам отличается на 84 дня (зона 3 — 168 дней, зона 6 — 252), поэтому
-- «Осенняя обрезка +120» давала 20 августа в Сибири и середину августа на юге, где до
-- листопада оставалось ещё три месяца.
--
-- Стало: у задачи появляется поле anchor.
--   anchor отсутствует или "start" — смещение от начала вегетации (поведение по умолчанию,
--     все весенние и летние работы не меняются);
--   anchor = "end" — смещение от КОНЦА вегетации; отрицательное значение = до его наступления.
--
-- Смещения (конец вегетации ≈ переход ниже +5 °C, около этого срока идёт листопад):
--   Осенняя подкормка          −21  до листопада, чтобы фосфор-калий успели усвоиться
--   Осенняя обрезка кустов      +7  после листопада, когда виден скелет куста
--   Осенняя обрезка деревьев   +14  после полного листопада
--   Пригибание на зимовку      +14  после листопада, до устойчивых морозов
--   Побелка стволов (осень)    +21  поздняя осень, до морозов и яркого зимнего солнца
--
-- Трогаем только культуры, у которых есть осенние/зимние задачи (15 задач, миграция 038).

UPDATE crops c SET care_tasks = sub.tasks
FROM (
  SELECT c2.id,
         jsonb_agg(
           CASE
             WHEN t->>'name' ILIKE '%побелка стволов%'
               THEN t || '{"anchor":"end","day_offset":21}'::jsonb
             WHEN t->>'name' ILIKE '%осенняя подкормка%'
               THEN t || '{"anchor":"end","day_offset":-21}'::jsonb
             WHEN t->>'name' ILIKE '%зимовку%'
               THEN t || '{"anchor":"end","day_offset":14}'::jsonb
             WHEN t->>'name' ILIKE '%осенн%обрезка%' AND c2.category = 'tree'
               THEN t || '{"anchor":"end","day_offset":14}'::jsonb
             WHEN t->>'name' ILIKE '%осенн%обрезка%'
               THEN t || '{"anchor":"end","day_offset":7}'::jsonb
             ELSE t
           END
           ORDER BY ord
         ) AS tasks
  FROM crops c2, jsonb_array_elements(c2.care_tasks) WITH ORDINALITY AS a(t, ord)
  WHERE jsonb_typeof(c2.care_tasks) = 'array'
    AND EXISTS (
      SELECT 1 FROM jsonb_array_elements(c2.care_tasks) x
      WHERE x->>'name' ~* '(^|[^а-яё])(осен|зимовку)'
    )
  GROUP BY c2.id
) sub
WHERE c.id = sub.id;
