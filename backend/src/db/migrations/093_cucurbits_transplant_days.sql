-- Migration 093: рассадный способ для кабачка, тыквы и патиссона.
-- Run (на VPS под postgres): sudo -u postgres psql -d dacha_db -f 093_cucurbits_transplant_days.sql
--
-- С 2026-09-24 выбор «Сразу в грунт / Через рассаду» в форме посадки показывается только у культур
-- с transplant_days (у моркови, картофеля, кустов и т.п. способ один). У тыквенных, кроме огурца,
-- transplant_days был пуст — хотя в средней полосе их обычно сажают рассадой (у кабачка в
-- climate_zones даже заданы окна высадки рассады). Без правки они потеряли бы выбор.
-- 30 дней — как у огурца: рассада тыквенных растёт 25–30 дней и плохо переносит перерастание.

UPDATE crops SET transplant_days = 30
WHERE name IN ('Кабачок', 'Тыква', 'Патиссон') AND transplant_days IS NULL;
