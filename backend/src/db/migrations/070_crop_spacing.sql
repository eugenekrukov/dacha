-- 070_crop_spacing.sql
-- Схема посадки культур: расстояние между растениями в ряду и между рядами.
-- Предпосылка для подсказки вместимости грядки (docs/ux-roadmap.md) — без этих данных
-- невозможно посчитать, сколько растений влезет на грядку заданного размера.
--
-- Значения — типичные ориентиры для дачных условий средней полосы (стандартная агротехника,
-- та же степень достоверности, что и у уже имеющихся watering_details/fertilizing_schedule).
-- Это ориентир для подсказки, не жёсткая норма — на карточке культуры их можно будет
-- поправить вручную (PUT /crops/:id, как и остальную агрономию).
--
-- Для кустарников и деревьев (малина, смородина, крыжовник, ежевика, жимолость, яблоня, груша,
-- вишня, черешня, слива) поля тоже заполнены (расстояние между кустами/деревьями и между рядами),
-- но подсказка вместимости грядки для них малоприменима — крупные многолетники обычно сажают
-- не в короб-грядку, а прямо на участке. Данные заведены для полноты схемы посадки (шаг 1 из
-- «схема → размеры грядки → подсказка»), фильтр «эта культура для грядки» — отдельная задача,
-- если понадобится.

