const YEAR = 365

// День года в 1..365 (окна «до начала сезона» уходят в минус, осенние — за 365).
function wrapDoy(d) {
  return ((Math.round(d) - 1) % YEAR + YEAR) % YEAR + 1
}

function dayOfYear(date) {
  return Math.floor((date - new Date(date.getFullYear(), 0, 0)) / 86400000)
}

/** Окно работы в днях года { from, to } для сезона участка. from > to — окно через Новый год. */
function workWindow(work, seasonStart, seasonEnd) {
  const base = work.anchor === 'spring' ? seasonStart : work.anchor === 'autumn' ? seasonEnd : 0
  return { from: wrapDoy(base + work.from), to: wrapDoy(base + work.to) }
}

// Сколько дней от d до конца окна; -1, если d в окно не попадает.
function daysLeftInWindow(d, { from, to }) {
  const inside = from <= to ? d >= from && d <= to : d >= from || d <= to
  if (!inside) return -1
  return (to - d + YEAR) % YEAR
}

/**
 * Работы на ближайшую неделю: окно работы пересекается с [сегодня; сегодня + 6].
 * Сортировка: культуры, которые есть на участке, → окно закрывается раньше → остальное.
 *
 * @param {object} p
 * @param {Date}   p.today
 * @param {number} p.seasonStart   день года начала сезона (факт или норма зоны)
 * @param {number} p.seasonEnd     день года конца сезона
 * @param {string} [p.zone]        климатическая зона участка (фильтр по work.zones)
 * @param {Set<string>} [p.gardenCrops] crops.name активных посадок участка
 * @param {number} [p.limit]
 */
function worksForWeek({ today, seasonStart, seasonEnd, zone = null, gardenCrops = new Set(), limit = 8 }) {
  const todayDoy = dayOfYear(today)
  const year = today.getFullYear()
  const out = []
  for (const w of WORKS) {
    if (w.zones && zone != null && !w.zones.includes(String(zone))) continue
    const win = workWindow(w, seasonStart, seasonEnd)
    let daysLeft = -1
    for (let i = 0; i < 7 && daysLeft < 0; i++) {
      const left = daysLeftInWindow(wrapDoy(todayDoy + i), win)
      if (left >= 0) daysLeft = left + i
    }
    if (daysLeft < 0) continue
    // Ключ для «Сделано/Не актуально» на клиенте: год, в котором окно ЗАКРЫВАЕТСЯ — иначе
    // скрытая в декабре зимняя работа снова всплыла бы 1 января.
    const crops = [].concat(w.crop || [])
    const key = `${w.id}:${todayDoy + daysLeft > YEAR ? year + 1 : year}`
    out.push({
      id: w.id, key, title: w.title, details: w.details, category: w.category,
      crop: crops[0] || null, in_garden: crops.some(c => gardenCrops.has(c)), days_left: daysLeft,
    })
  }
  out.sort((a, b) => (b.in_garden - a.in_garden) || (a.days_left - b.days_left))
  return out.slice(0, limit)
}

module.exports = { WORKS, worksForWeek, workWindow, wrapDoy }
